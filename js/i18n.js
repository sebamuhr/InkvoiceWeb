const LANG_CODE = { English:'en', German:'de', Spanish:'es', French:'fr' };
export function currentLang(){ return LANG_CODE[(getProfile().appLanguage)] || 'en'; }
// Normalise a language WORD ('German') or code ('de') to a code. Used for the invoice PDF, which
// renders in the invoice's OWN language (invoiceLanguage), not the app language.
export function langCode(word){ return LANG_CODE[word] || (['en','de','es','fr'].includes(word) ? word : 'en'); }

