// t('English string') returns the string in the user's chosen App Language (Profile →
// App Language), falling back to the English text if there's no translation yet. So wrapping
// a UI string in t() is always safe. The DE/ES/FR maps below are the real, human translations
// reused from the Android app's strings.xml (values-de / -es / -fr) — keyed by the ENGLISH text.
